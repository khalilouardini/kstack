from __future__ import annotations

import hashlib
import os
from importlib.machinery import SourceFileLoader
from importlib.util import module_from_spec, spec_from_loader
from pathlib import Path
import subprocess
import tempfile
import unittest

HELPER = Path(__file__).resolve().parents[1] / 'bin/installation-status'
loader = SourceFileLoader('installation_status', str(HELPER))
module = module_from_spec(spec_from_loader(loader.name, loader))
loader.exec_module(module)


class InstallationStatus(unittest.TestCase):
    def setUp(self):
        self.scratch = tempfile.TemporaryDirectory()
        self.addCleanup(self.scratch.cleanup)
        self.base = Path(self.scratch.name).resolve()
        self.root = self.base / 'projects/stack checkout'
        self.home = self.base / 'user'
        self.codex = self.home / '.codex'
        self.state = self.home / '.kstack'
        self.root.mkdir(parents=True)
        self.state.mkdir(parents=True)
        self.git('init', '-q', '-b', 'main')
        self.canonical = {}
        for name in ['example-one', 'example-two']:
            path = self.root / 'core' / name / 'SKILL.md'
            path.parent.mkdir(parents=True)
            path.write_text(f'---\nname: {name}\nversion: 1.0.0\ndescription: Synthetic {name}.\n---\n\nProcedure.\n')
            self.canonical[name] = path
            claude = self.home / '.claude/skills' / name
            claude.parent.mkdir(parents=True, exist_ok=True)
            claude.symlink_to(path.parent)
            self.pointer(self.codex / 'skills' / name / 'SKILL.md', path)
        (self.root / 'bin').mkdir()
        (self.root / 'bin/install').write_text('# synthetic installer fixture\n')
        (self.root / 'CONVENTIONS.md').write_text('Synthetic conventions.\n')
        self.git('add', 'core/example-one/SKILL.md', 'core/example-two/SKILL.md', 'bin/install', 'CONVENTIONS.md')
        self.git('commit', '-qm', 'initial fixture')
        self.git('update-ref', 'refs/remotes/origin/main', self.git('rev-parse', 'HEAD'))
        self.git('symbolic-ref', 'refs/remotes/origin/HEAD', 'refs/remotes/origin/main')
        (self.state / 'stack-root').write_text(str(self.root)+'\n')

    def git(self, *args):
        return subprocess.check_output(['git', '-C', str(self.root), '-c', 'user.name=Fixture',
                                        '-c', 'user.email=fixture@example.invalid',
                                        '-c', 'commit.gpgsign=false', *args], text=True).strip()

    def pointer(self, path, canonical):
        meta = module.metadata(canonical)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text('---\n'+'\n'.join(f'{key}: {value}' for key,value in meta.items())+
                        '\n---\n\n<!-- kstack pointer — generated by bin/install; do not edit. -->\n\n'
                        f'Read `{canonical}` with your file-reading tool and follow it exactly.\n')

    def audit(self, projects=None, parents=None):
        return module.audit(self.root, self.home, self.codex, self.state, projects or [], parents or [])

    def test_both_hosts_current_at_same_commit(self):
        result = self.audit()
        self.assertEqual(result['shared_status'], 'CURRENT')
        for info in result['hosts'].values():
            self.assertEqual((info['current'], info['expected'], info['issues']), (2, 2, []))
        self.assertFalse(result['complete_machine_audit'])
        self.assertIn('does not fetch', result['source']['freshness'])

    def test_dirty_source_does_not_certify_current(self):
        (self.root / 'uncommitted.txt').write_text('preserve this')
        result = self.audit()
        self.assertEqual(result['shared_status'], 'NEEDS_ATTENTION')
        self.assertIn('?? uncommitted.txt', result['source']['dirty'])

    def test_matching_adapters_do_not_hide_source_ahead_of_main(self):
        self.git('commit', '--allow-empty', '-qm', 'unpublished fixture')
        self.assertEqual(self.audit()['shared_status'], 'NEEDS_ATTENTION')

    def test_detached_source_is_disclosed(self):
        self.git('switch', '--detach', '-q')
        result = self.audit()
        self.assertEqual(result['source']['branch'], 'DETACHED')
        self.assertEqual(result['shared_status'], 'NEEDS_ATTENTION')

    def test_operation_in_progress_is_disclosed(self):
        path = Path(self.git('rev-parse', '--path-format=absolute', '--git-path', 'MERGE_HEAD'))
        path.write_text(self.git('rev-parse', 'HEAD')+'\n')
        result = self.audit()
        self.assertIn('MERGE_HEAD', result['source']['operations'])
        self.assertEqual(result['shared_status'], 'NEEDS_ATTENTION')

    def test_missing_record_is_not_current(self):
        (self.state / 'stack-root').unlink()
        self.assertEqual(self.audit()['shared_status'], 'NEEDS_ATTENTION')

    def test_wrong_root_record_is_not_current(self):
        (self.state / 'stack-root').write_text(str(self.base / 'different checkout'))
        self.assertEqual(self.audit()['shared_status'], 'NEEDS_ATTENTION')

    def test_missing_default_ref_is_honest(self):
        self.git('symbolic-ref', '--delete', 'refs/remotes/origin/HEAD')
        result = self.audit()
        self.assertIsNone(result['source']['local_default_sha'])
        self.assertEqual(result['shared_status'], 'NEEDS_ATTENTION')

    def test_wrong_and_broken_claude_links(self):
        for name, target in [('example-one', self.base / 'other'), ('example-two', self.base / 'missing')]:
            path = self.home / '.claude/skills' / name
            path.unlink()
            path.symlink_to(target)
        self.assertEqual(self.audit()['hosts']['claude']['current'], 0)

    def test_existing_claude_directory_is_preserved_and_reported(self):
        path = self.home / '.claude/skills/example-one'
        path.unlink()
        path.mkdir()
        note = path / 'custom.txt'
        note.write_text('keep')
        self.assertEqual(self.audit()['hosts']['claude']['current'], 1)
        self.assertEqual(note.read_text(), 'keep')

    def test_codex_frontmatter_drift_in_every_copied_field(self):
        path = self.codex / 'skills/example-one/SKILL.md'
        original = path.read_text()
        for before, after in [('version: 1.0.0', 'version: 0.1.0'),
                              ('name: example-one', 'name: different'),
                              ('description: Synthetic', 'description: Changed')]:
            with self.subTest(field=before):
                path.write_text(original.replace(before, after))
                self.assertEqual(self.audit()['hosts']['codex']['current'], 1)
        path.write_text(original)

    def test_codex_wrong_source_even_with_matching_version(self):
        path = self.codex / 'skills/example-one/SKILL.md'
        path.write_text(path.read_text().replace(str(self.root), str(self.base / 'other')))
        self.assertEqual(self.audit()['hosts']['codex']['current'], 1)

    def test_relative_pointer_source_is_not_globally_reliable(self):
        path = self.codex / 'skills/example-one/SKILL.md'
        relative = os.path.relpath(self.canonical['example-one'], Path.cwd())
        path.write_text(path.read_text().replace(str(self.canonical['example-one']), relative))
        self.assertEqual(self.audit()['hosts']['codex']['current'], 1)

    def test_custom_codex_file_is_preserved(self):
        path = self.codex / 'skills/example-one/SKILL.md'
        path.write_text('Personal skill, not a generated adapter.\n')
        self.assertEqual(self.audit()['hosts']['codex']['current'], 1)
        self.assertEqual(path.read_text(), 'Personal skill, not a generated adapter.\n')

    def test_codex_symlink_destination_is_not_reported_as_installer_ready(self):
        path = self.codex / 'skills/example-one/SKILL.md'
        path.unlink()
        path.symlink_to(self.canonical['example-one'])
        result = self.audit()
        self.assertEqual(result['hosts']['codex']['current'], 1)
        self.assertIn('symlinked', result['hosts']['codex']['issues'][0]['reason'])

    def test_missing_adapters_are_counted(self):
        (self.codex / 'skills/example-one/SKILL.md').unlink()
        self.assertEqual(self.audit()['hosts']['codex']['current'], 1)

    def test_orphaned_generated_pointer_is_not_ignored(self):
        self.pointer(self.codex / 'skills/removed/SKILL.md', self.canonical['example-one'])
        result = self.audit()
        self.assertEqual(result['shared_status'], 'NEEDS_ATTENTION')
        self.assertIn('orphaned', result['hosts']['codex']['issues'][0]['reason'])

    def test_project_copy_and_global_status_are_separate(self):
        project = self.base / 'projects/consumer'
        file = project / '.claude/skills/example-one/SKILL.md'
        file.parent.mkdir(parents=True)
        file.write_text(self.canonical['example-one'].read_text())
        result = self.audit(parents=[project.parent])
        self.assertEqual(result['shared_status'], 'CURRENT')
        self.assertEqual(len(result['projects']['overrides']), 1)
        self.assertEqual(result['projects']['overrides'][0]['project'], str(project))

    def test_live_project_link_is_not_a_distinct_copy(self):
        project = self.base / 'consumer'
        directory = project / '.agents/skills'
        directory.mkdir(parents=True)
        (directory / 'example-one').symlink_to(self.canonical['example-one'].parent)
        self.assertEqual(self.audit(projects=[project])['projects']['overrides'], [])

    def test_project_generated_pointer_to_same_source_is_recognized(self):
        project = self.base / 'consumer'
        self.pointer(project / '.agents/skills/example-one/SKILL.md', self.canonical['example-one'])
        self.assertEqual(self.audit(projects=[project])['projects']['overrides'], [])

    def test_registered_worktree_outside_parent_is_checked(self):
        worktree = self.base / 'external worktree'
        self.git('worktree', 'add', '--detach', '-q', str(worktree))
        file = worktree / '.agents/skills/example-one/SKILL.md'
        file.parent.mkdir(parents=True)
        file.write_text('A local copy.')
        result = self.audit()
        self.assertIn(str(worktree), result['projects']['checked'])
        self.assertEqual(len(result['projects']['overrides']), 1)

    def test_unavailable_project_is_a_coverage_error(self):
        result = self.audit(projects=[self.base / 'absent'])
        self.assertTrue(result['projects']['errors'])

    def test_scan_does_not_pretend_to_recurse_every_directory(self):
        nested = self.base / 'projects/data/nested/.claude/skills/example-one/SKILL.md'
        nested.parent.mkdir(parents=True)
        nested.write_text('copy')
        result = self.audit(parents=[self.root.parent])
        self.assertEqual(result['projects']['overrides'], [])
        self.assertFalse(result['complete_machine_audit'])

    def test_audit_writes_no_adapters_state_or_worktree_files(self):
        def snapshot():
            return {str(p):hashlib.sha256(p.read_bytes()).hexdigest()
                    for base in [self.home, self.root] for p in base.rglob('*')
                    if p.is_file() and '.git' not in p.parts}
        before = snapshot()
        self.audit(parents=[self.root.parent])
        self.assertEqual(snapshot(), before)

    def test_missing_canonical_contract_is_not_a_stack_installation(self):
        (self.root / 'CONVENTIONS.md').unlink()
        with self.assertRaises(ValueError):
            module.skills(self.root)

    def test_invalid_canonical_directory_is_not_an_empty_success(self):
        with self.assertRaises(ValueError):
            module.skills(self.base)


if __name__ == '__main__':
    unittest.main()
